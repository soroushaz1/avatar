const readLang = () => {
  try {
    return localStorage.getItem('avatar.lang');
  } catch {
    return null;
  }
};

export let lang = STRINGS[readLang()] ? readLang() : 'fa';

export const locale = () => (lang === 'fa' ? 'fa-IR' : 'en-US');

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

export const formatNumber = (n) => new Intl.NumberFormat(locale()).format(n);
export const formatDate = (d) => new Intl.DateTimeFormat(locale(), { dateStyle: 'medium' }).format(d);

// Applies the current language to the document and every element marked for translation.
export function applyLanguage(root = document) {
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.title = t('title');
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('description'));
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}

export function setLanguage(next) {
  if (!STRINGS[next]) return;
  lang = next;
  try {
    localStorage.setItem('avatar.lang', next);
  } catch { /* storage unavailable */ }
  applyLanguage();
}
